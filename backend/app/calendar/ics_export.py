"""
RFC 5545 Compliant iCalendar (.ics) Exporter (Req 5).
Generates valid iCalendar files with IST timezone definitions,
event titles, platform tags, clip descriptions, copy text,
and AI rationale.
"""

from datetime import datetime, timezone, timedelta
from typing import Any, Dict, List, Optional, Union

from app.calendar.models import IST, CalendarItemResponse


def escape_rfc5545_text(text: Optional[str]) -> str:
    r"""
    Escapes characters per RFC 5545 Section 3.3.11:
    - Backslash (\) -> \\
    - Semicolon (;) -> \;
    - Comma (,) -> \,
    - Newlines -> \n
    """
    if not text:
        return ""
    # Normalize newlines
    normalized = text.replace("\r\n", "\n").replace("\r", "\n")
    # Escape backslash first
    escaped = normalized.replace("\\", "\\\\")
    # Escape semicolon and comma
    escaped = escaped.replace(";", "\\;").replace(",", "\\,")
    # Escape newlines
    escaped = escaped.replace("\n", "\\n")
    return escaped


def fold_line(line: str, max_octets: int = 75) -> str:
    """
    Folds lines exceeding max_octets (RFC 5545 Section 3.1).
    Continuation lines start with a single whitespace.
    """
    encoded = line.encode("utf-8")
    if len(encoded) <= max_octets:
        return line

    chunks: List[str] = []
    current_line = bytearray()

    for char in line:
        char_bytes = char.encode("utf-8")
        if len(current_line) + len(char_bytes) > max_octets:
            chunks.append(current_line.decode("utf-8"))
            current_line = bytearray(b" ")  # Start folded line with single space
        current_line.extend(char_bytes)

    if current_line:
        chunks.append(current_line.decode("utf-8"))

    return "\r\n".join(chunks)


def parse_to_ist_datetime(val: Union[str, datetime]) -> datetime:
    """Parses ISO string or datetime into IST datetime."""
    if isinstance(val, datetime):
        if val.tzinfo is None:
            return val.replace(tzinfo=IST)
        return val.astimezone(IST)
    
    # String parsing
    clean_val = val.replace("Z", "+00:00")
    dt = datetime.fromisoformat(clean_val)
    if dt.tzinfo is None:
        return dt.replace(tzinfo=IST)
    return dt.astimezone(IST)


def generate_ics_calendar(
    items: List[Union[CalendarItemResponse, Dict[str, Any]]],
    calendar_name: str = "Reel Content Schedule (IST)",
    calendar_description: str = "Automated social content schedule generated by Reel Studio in IST",
) -> str:
    """
    Constructs an RFC 5545 compliant VCALENDAR document.
    Includes VTIMEZONE for Asia/Kolkata (IST), event UID, DTSTART, DTEND,
    SUMMARY, and DESCRIPTION containing platform, clip hook, copy, and AI rationale.
    """
    now_utc = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")

    lines: List[str] = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//Reel Content Repurposing Studio//Content Calendar//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        f"X-WR-CALNAME:{escape_rfc5545_text(calendar_name)}",
        f"X-WR-CALDESC:{escape_rfc5545_text(calendar_description)}",
        "X-WR-TIMEZONE:Asia/Kolkata",
        # VTIMEZONE definition for IST
        "BEGIN:VTIMEZONE",
        "TZID:Asia/Kolkata",
        "X-LIC-LOCATION:Asia/Kolkata",
        "BEGIN:STANDARD",
        "TZOFFSETFROM:+0530",
        "TZOFFSETTO:+0530",
        "TZNAME:IST",
        "DTSTART:19700101T000000",
        "END:STANDARD",
        "END:VTIMEZONE",
    ]

    for item in items:
        # Normalize item
        if isinstance(item, CalendarItemResponse):
            item_id = item.id
            title = item.title or "Untitled Post"
            platform = (item.platform or "general").upper()
            scheduled_str = item.scheduled_for or item.slot_time_ist
            status = item.status or "scheduled"
            rationale = item.slot_reason or item.ai_rationale or ""
            copy_text = item.copy_text or ""
            hook = item.hook or ""
            hashtags = " ".join(item.hashtags) if item.hashtags else ""
        elif isinstance(item, dict):
            item_id = item.get("id", "evt-reel")
            title = item.get("title") or item.get("clip") or "Untitled Post"
            platform = str(item.get("platform", "general")).upper()
            scheduled_str = item.get("scheduled_for") or item.get("slot_time_ist") or item.get("scheduled_time")
            status = item.get("status", "scheduled")
            rationale = item.get("slot_reason") or item.get("ai_rationale") or item.get("rationale") or ""
            copy_text = item.get("copy_text") or ""
            hook = item.get("hook") or ""
            tags = item.get("hashtags")
            hashtags = " ".join(tags) if isinstance(tags, list) else (tags or "")
        else:
            continue

        if not scheduled_str:
            continue

        start_dt = parse_to_ist_datetime(scheduled_str)
        # Default duration: 30 minutes
        end_dt = start_dt + timedelta(minutes=30)

        dtstart_formatted = start_dt.strftime("%Y%m%dT%H%M%S")
        dtend_formatted = end_dt.strftime("%Y%m%dT%H%M%S")

        # Build clean event description
        desc_parts = [
            f"Platform: {platform}",
            f"Status: {status.title()}",
        ]
        if hook:
            desc_parts.append(f"Hook: {hook}")
        if copy_text and copy_text != hook:
            desc_parts.append(f"Copy: {copy_text}")
        if hashtags:
            desc_parts.append(f"Hashtags: {hashtags}")
        if rationale:
            desc_parts.append(f"AI Slot Rationale: {rationale}")
        desc_parts.append("Managed by Reel Content Repurposing Studio (IST)")

        full_description = "\n".join(desc_parts)

        # Event fields
        event_lines = [
            "BEGIN:VEVENT",
            f"UID:{item_id}@reelstudio.ai",
            f"DTSTAMP:{now_utc}",
            f"DTSTART;TZID=Asia/Kolkata:{dtstart_formatted}",
            f"DTEND;TZID=Asia/Kolkata:{dtend_formatted}",
            f"SUMMARY:[{platform}] {escape_rfc5545_text(title)}",
            f"DESCRIPTION:{escape_rfc5545_text(full_description)}",
            f"STATUS:CONFIRMED",
            f"CATEGORIES:CONTENT,{platform}",
            "TRANSP:OPAQUE",
            "END:VEVENT",
        ]

        lines.extend(event_lines)

    lines.append("END:VCALENDAR")

    # Apply folding and CRLF line endings
    folded_lines = [fold_line(l) for l in lines]
    return "\r\n".join(folded_lines) + "\r\n"
